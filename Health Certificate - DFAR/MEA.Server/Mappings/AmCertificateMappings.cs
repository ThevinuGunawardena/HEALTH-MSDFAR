        DescCommon                      = dto.DescCommon,
        HsCode                          = dto.HsCode,
        Quantity                        = dto.Quantity,
        TemperatureAmbient              = dto.TemperatureAmbient,
        TemperatureChilled              = dto.TemperatureChilled,
