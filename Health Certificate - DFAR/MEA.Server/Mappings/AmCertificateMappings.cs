        CompanyUserId                   = companyUserId,
        CreatedAt                       = DateTime.UtcNow,
        ConsignorName                   = dto.ConsignorName,
        ConsignorAddress                = dto.ConsignorAddress,
        ConsignorPostal                 = dto.ConsignorPostal,
